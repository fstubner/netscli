import { rm } from "node:fs/promises";
import { join } from "node:path";
import { writeFileAtomic } from "../utils/atomic-file.js";
import {
  MARKERS,
  countManagedBlocks,
  matchLineEndings,
  normalizeNewlines,
  removeManagedBlocks,
} from "./managed-block.js";
import { readUtf8IfExists, writeIfChanged } from "./file-io.js";
